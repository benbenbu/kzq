void LCD_DisplayChar(unsigned int x, unsigned char y, char ch, unsigned char disp_size, unsigned char inverse) {
    unsigned char uc_ch = (unsigned char)ch;
    unsigned char *original_data = NULL;
    unsigned char converted_data[80];  // ??????????????
    unsigned char col_lsb, col_msb;
    unsigned char inv_mask = inverse ? 0xFF : 0x00;
    unsigned char row, col;
    unsigned char rows, cols_per_row, total_bytes;
    CharType char_type;
    
    // ?????????????Χ
    if (x >= LCD_WIDTH || y >= LCD_HEIGHT) {
        return;
    }
    
    // ?????????С???ò???
    switch (disp_size) {
        case 1:  // 8x6???
            rows = 8;
            cols_per_row = 3;
            total_bytes = 24;  // 8?? ?? 3???/?? = 24????
            char_type = CHAR_TYPE_8x6;
            
            // ???8x6?????????????????????
            if (uc_ch >= 0x20 && uc_ch <= 0x7F) {
                original_data = (unsigned char *)F8X6[(uc_ch - 0x20)];
            } else {
                return;  // ?????????
            }
            break;
            
        case 2:  // 16x9???
            rows = 16;
            cols_per_row = 5;  // ???5???
            total_bytes = 80;  // 16?? ?? 5???/?? = 80????
            char_type = CHAR_TYPE_16x9;
            
            // ???16x9?????????????
            if (uc_ch >= 0x20 && uc_ch <= 0x7F) {
                original_data = (unsigned char *)F16X9[(uc_ch - 0x20)];
            } else {
                return;  // ?????????
            }
            break;
            
        default:
            return;  // ???????????С
    }
    
    // ???ú????????
    ConvertChar(original_data, converted_data, char_type);
    
    // ?????е??
    col_lsb = 0x00 | (x & 0x0F);  // ?е????4λ
    col_msb = 0x10 | ((x & 0xF0) >> 4);  // ?е????4λ
    
    // ???????????д??LCD
    for (row = 0; row < rows; row++) {
        // ???????????Χ
        if ((y + row) >= LCD_HEIGHT) {
            break;
        }
        
        // ????RAM???
        LCD_WriteCmd(0x89);  // ????RAM???????
        LCD_WriteCmd(col_lsb);  // ?????е????4λ
        LCD_WriteCmd(col_msb);  // ?????е????4λ
        LCD_WriteCmd(0x60 | ((y + row) & 0x0F));  // ?????е????4λ
        LCD_WriteCmd(0x70 | (((y + row) & 0xF0) >> 4));  // ?????е????4λ
        
        // ???????е???????
        for (col = 0; col < cols_per_row; col++) {
            LCD_WriteData(converted_data[row * cols_per_row + col] ^ inv_mask);
        }
    }
    
    LCD_WriteCmd(0x88);  // ???RAM?????????
}

