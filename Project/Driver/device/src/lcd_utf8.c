typedef enum {
    CHAR_TYPE_8x6,   // 8x6?????????6???????24???
    CHAR_TYPE_16x9,  // 16x9?????????24???????80???
    CHAR_TYPE_16x18  // 16x18?????????48???????144???
} CharType;

/**
 * @brief ???????????UC1698 LCD??????
 * @param input ????????????????????char_type???
 * @param output ?????????????????С????char_type???
 * @param char_type ????????CHAR_TYPE_8x6??CHAR_TYPE_16x9??CHAR_TYPE_16x18
 * @return ???????0????????-1
 */
int ConvertChar(unsigned char* input, unsigned char* output, CharType char_type) {
    unsigned char rows, cols_per_row, input_bytes_per_row;
    unsigned char pixel_count;  // ??е???????
    
    // ??????????????ò???
    switch (char_type) {
        case CHAR_TYPE_8x6:
            rows = 8;
            pixel_count = 6;
            input_bytes_per_row = 1;  // ????1????8λ??
            cols_per_row = 3;  // 6?????? / 2?????????? = 3???/??
            break;
            
        case CHAR_TYPE_16x9:
            rows = 16;
            pixel_count = 9;
            input_bytes_per_row = 2;  // ????2????16λ??
            cols_per_row = 5;  // 9?????? / 2?????????? = 4.5???/?У?????????5
            break;
            
        case CHAR_TYPE_16x18:
            rows = 16;
            pixel_count = 18;
            input_bytes_per_row = 3;  // ????3????24λ??
            cols_per_row = 9;  // 18?????? / 2?????????? = 9???/??
            break;
            
        default:
            return -1;
    }
    
    // ????????
    for (unsigned char row = 0; row < rows; row++) {
        // ???????????????????1????
        for (unsigned char col = 0; col < cols_per_row; col++) {
            unsigned char pixel1 = 0, pixel2 = 0;
            unsigned char pixel_pos = col * 2;
            
            // ???????Ч?????
            if (pixel_pos < pixel_count) {
                unsigned char byte_pos = row * input_bytes_per_row;
                unsigned char bit_pos;
                
                // ?????????????????λ???????
                if (char_type == CHAR_TYPE_8x6) {
                    // 8x6????????????????λ????λ??????????????
                    bit_pos = pixel_pos % 8;
                    
                    // ?????????????
                    pixel1 = (input[byte_pos + pixel_pos / 8] >> bit_pos) & 0x01;
                    
                    // ??????????????????????
                    if (pixel_pos + 1 < pixel_count) {
                        bit_pos = (pixel_pos + 1) % 8;
                        pixel2 = (input[byte_pos + (pixel_pos + 1) / 8] >> bit_pos) & 0x01;
                    }
                } else {
                    // 16x9??16x18????????????????λ????λ
                    bit_pos = 7 - pixel_pos;
                    
                    // ?????????????
                    if (bit_pos < 8) {
                        pixel1 = (input[byte_pos] >> bit_pos) & 0x01;
                    } else {
                        pixel1 = (input[byte_pos + 1] >> (bit_pos - 8)) & 0x01;
                    }
                    
                    // ??????????????????????
                    if (pixel_pos + 1 < pixel_count) {
                        bit_pos = 7 - (pixel_pos + 1);
                        if (bit_pos < 8) {
                            pixel2 = (input[byte_pos] >> bit_pos) & 0x01;
                        } else {
                            pixel2 = (input[byte_pos + 1] >> (bit_pos - 8)) & 0x01;
                        }
                    }
                }
            }
            
            // ???????????? (????????????4λ??λ??)
            output[row * cols_per_row + col] = (pixel1 ? 0xF0 : 0x00) | (pixel2 ? 0x0F : 0x00);
        }
    }
    
    return 0;
}












